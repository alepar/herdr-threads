use serde::{Deserialize, Deserializer, Serialize};

macro_rules! id {
    ($name:ident) => {
        #[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
        #[serde(transparent)]
        pub struct $name(String);
        impl $name {
            pub fn parse(value: impl Into<String>) -> Result<Self, &'static str> {
                let value = value.into();
                if value.is_empty()
                    || value.len() > 128
                    || value.bytes().any(|b| !b.is_ascii_graphic())
                {
                    return Err("invalid opaque id");
                }
                Ok(Self(value))
            }
            pub fn new(value: impl Into<String>) -> Self {
                Self::parse(value).expect("valid opaque id")
            }
            pub fn as_str(&self) -> &str {
                &self.0
            }
        }
        impl<'de> Deserialize<'de> for $name {
            fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
                let value = String::deserialize(deserializer)?;
                Self::parse(value).map_err(serde::de::Error::custom)
            }
        }
    };
}
id!(SeatId);
id!(ThreadId);
/// Server message IDs exclude the private `local:` recovery-token namespace.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(transparent)]
pub struct MessageId(String);
impl MessageId {
    pub fn parse(value: impl Into<String>) -> Result<Self, &'static str> {
        let value = value.into();
        if value.is_empty()
            || value.len() > 128
            || value.starts_with("local:")
            || value.bytes().any(|b| !b.is_ascii_graphic())
        {
            return Err("invalid message id");
        }
        Ok(Self(value))
    }
    pub fn new(value: impl Into<String>) -> Self {
        Self::parse(value).expect("valid message id")
    }
    pub fn as_str(&self) -> &str {
        &self.0
    }
}
impl<'de> Deserialize<'de> for MessageId {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Self::parse(value).map_err(serde::de::Error::custom)
    }
}
