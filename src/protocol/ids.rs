/// Private journal lookup token; it never names a server receipt or message.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(transparent)]
pub struct LocalRecoveryRef(String);
impl LocalRecoveryRef {
    pub fn parse(value: impl Into<String>) -> Result<Self, &'static str> {
        let value = value.into();
        if !value.starts_with("local:")
            || value.len() <= "local:".len()
            || value.len() > 64
            || value.bytes().any(|b| !b.is_ascii_graphic())
        {
            return Err("invalid local recovery reference");
        }
        Ok(Self(value))
    }
    pub fn as_str(&self) -> &str {
        &self.0
    }
}
impl<'de> Deserialize<'de> for LocalRecoveryRef {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Self::parse(value).map_err(serde::de::Error::custom)
    }
}

/// Prefixes for newly minted public IDs. The node tag and the eight-character
/// base62 suffix follow the prefix directly (`<prefix><tag><8>`). Persisted IDs
/// with older shapes stay opaque and are never rewritten.
pub mod prefix {
    pub const SEAT: &str = "s";
    pub const THREAD: &str = "t";
    pub const INVITATION: &str = "i";
    pub const REQUIREMENT: &str = "q";
    pub const RETIREMENT: &str = "r";
    pub const EVENT: &str = "e";
    /// Send preparation; its ordinary message is `m<same tag and suffix>`.
    pub const SEND_PREPARATION: &str = "p";
    pub const MESSAGE: &str = "m";
    /// Service notification preparation; its message is `n<same tag and suffix>`.
    pub const NOTIFY_PREPARATION: &str = "np";
    pub const NOTIFY: &str = "n";
}

/// Length of the random base62 suffix of a newly generated public ID:
/// 62^8 ≈ 2^47.6 values per node tag. Collisions are still detected and
/// regenerated by the store (`store::public_ids`).
pub const PUBLIC_ID_SUFFIX_LEN: usize = 8;

/// Length of the node tag that follows the prefix of a public ID.
pub const NODE_TAG_LEN: usize = 3;

/// Characters after the prefix of a public ID: `<tag><8>`.
const PUBLIC_ID_BODY_LEN: usize = NODE_TAG_LEN + PUBLIC_ID_SUFFIX_LEN;

pub(crate) const BASE62: &[u8; 62] =
    b"0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz";

/// A fresh random base62 suffix of [`PUBLIC_ID_SUFFIX_LEN`] characters.
///
/// The entropy comes from the OS CSPRNG (via `uuid::Uuid::new_v4`): the 112
/// bits of a v4 UUID outside its version and variant bytes (bytes 6 and 8 are
/// skipped whole, so 10 random bits there are discarded: 4 beside the version
/// nibble in byte 6 and 6 beside the variant bits in byte 8) are reduced modulo
/// 62^8. 112 bits is 14 bytes x 8, and the bias is about 62^8 / 2^112 ≈ 2^-64,
/// below 2^-56.
pub fn public_id_suffix() -> String {
    let bytes = uuid::Uuid::new_v4().into_bytes();
    let mut random: u128 = 0;
    for (index, byte) in bytes.iter().enumerate() {
        // Byte 6 holds the version nibble, byte 8 the variant bits.
        if index != 6 && index != 8 {
            random = (random << 8) | u128::from(*byte);
        }
    }
    base62_digits(random, PUBLIC_ID_SUFFIX_LEN)
}

/// `len` base62 digits of `n`, least significant first (first emitted first).
pub(crate) fn base62_digits(mut n: u128, len: usize) -> String {
    let mut out = String::with_capacity(len);
    for _ in 0..len {
        out.push(char::from(BASE62[(n % 62) as usize]));
        n /= 62;
    }
    out
}

/// A fresh public ID `<prefix><tag><8 base62 chars>`, e.g. `sQ7ak3Fq9a2B`.
/// Callers that persist it must go through `store::public_ids`, which
/// supplies the tag from the `local_node` row and regenerates on collision.
pub fn generate_public_id(prefix: &str, tag: &NodeTag) -> String {
    format!("{prefix}{tag}{}", public_id_suffix())
}

/// Split `value` into its node tag and random suffix when it is exactly
/// `<prefix><tag><8 base62 chars>`. The body length is checked exactly, so
/// `np...` (13 chars) never parses as an `n` id and `n...` (12 chars) never as
/// an `np` id.
pub fn public_id_parts<'a>(prefix: &str, value: &'a str) -> Option<(NodeTag, &'a str)> {
    let body = value.strip_prefix(prefix)?;
    if body.len() != PUBLIC_ID_BODY_LEN || !body.bytes().all(|b| b.is_ascii_alphanumeric()) {
        return None;
    }
    let (tag, suffix) = body.split_at(NODE_TAG_LEN);
    Some((tag.parse().ok()?, suffix))
}

/// True when `value` is `<prefix><tag><8 base62 chars>`.
pub fn is_public_id(prefix: &str, value: &str) -> bool {
    public_id_parts(prefix, value).is_some()
}

fn derived_message_id(
    preparation: &str,
    compact_preparation: &str,
    compact_message: &str,
) -> Option<String> {
    let (tag, suffix) = public_id_parts(compact_preparation, preparation)?;
    Some(format!("{compact_message}{tag}{suffix}"))
}

/// Derive the message belonging to a send preparation (`p<tag><8>` to `m<tag><8>`).
pub fn send_message_id_for_preparation(preparation: &str) -> Option<String> {
    derived_message_id(preparation, prefix::SEND_PREPARATION, prefix::MESSAGE)
}

/// Derive the message belonging to a service notification preparation
/// (`np<tag><8>` to `n<tag><8>`).
pub fn notification_message_id_for_preparation(preparation: &str) -> Option<String> {
    derived_message_id(preparation, prefix::NOTIFY_PREPARATION, prefix::NOTIFY)
}

/// Recover the preparation belonging to a notification message.
pub fn notification_preparation_id_for_message(message: &str) -> Option<String> {
    derived_message_id(message, prefix::NOTIFY, prefix::NOTIFY_PREPARATION)
}

/// Prefix of a deterministic direct-thread ID.
pub const DIRECT_THREAD_PREFIX: &str = "d";

/// Base62 digits after [`DIRECT_THREAD_PREFIX`]: 62^10 ≈ 2^59.5 values.
const DIRECT_THREAD_DIGITS: usize = 10;

const DIRECT_THREAD_DOMAIN: &[u8] = b"herdr-threads/direct/v1";

/// Why no direct-thread ID exists for a pair of seats.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DirectIdError {
    /// Both seats are the same seat: a direct thread needs two.
    SameSeat,
}

impl std::fmt::Display for DirectIdError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::SameSeat => f.write_str("a direct thread needs two different seats"),
        }
    }
}

impl std::error::Error for DirectIdError {}

/// The deterministic ID `d<10 base62>` of the direct thread between seats `a`
/// and `b`.
///
/// Owns: the pure pair-to-ID function. Pure and symmetric: `(a, b)` and
/// `(b, a)` give the same ID, the pair is ordered by `str` byte order, and the
/// hash input is `herdr-threads/direct/v1` then `u32 BE len ‖ bytes` for the
/// lower and then the higher seat id. It never hashes node IDs, reads no
/// store and keeps no state; the ID is the first 16 bytes of the SHA-256 as a
/// big-endian `u128`, written as 10 base62 digits. Wired nowhere yet
/// (ht-5fr.4 adopts it).
pub fn direct_thread_id(a: &SeatId, b: &SeatId) -> Result<ThreadId, DirectIdError> {
    use sha2::{Digest, Sha256};

    if a == b {
        return Err(DirectIdError::SameSeat);
    }
    let (lo, hi) = if a.as_str() <= b.as_str() {
        (a.as_str(), b.as_str())
    } else {
        (b.as_str(), a.as_str())
    };
    let mut hasher = Sha256::new();
    hasher.update(DIRECT_THREAD_DOMAIN);
    for seat in [lo, hi] {
        hasher.update((seat.len() as u32).to_be_bytes());
        hasher.update(seat.as_bytes());
    }
    let digest = hasher.finalize();
    let mut head = [0u8; 16];
    head.copy_from_slice(&digest[..16]);
    let digits = base62_digits(u128::from_be_bytes(head), DIRECT_THREAD_DIGITS);
    Ok(ThreadId::new(format!("{DIRECT_THREAD_PREFIX}{digits}")))
}

/// True when `value` has the shape of a [`direct_thread_id`].
pub fn is_direct_thread_id(value: &str) -> bool {
    value
        .strip_prefix(DIRECT_THREAD_PREFIX)
        .is_some_and(|body| {
            body.len() == DIRECT_THREAD_DIGITS && body.bytes().all(|b| b.is_ascii_alphanumeric())
        })
}

/// HostLocator: the wire name of one Herdr server, its canonical socket path.
///
/// Owns: the parse rules (absolute, 1..=4096 bytes, no NUL, no empty, `.` or
/// `..` component, no trailing `/`), string serde, and conversion to a path for
/// attach and handoff-namespace comparison.
/// Hides: that a server is identified by a filesystem path.
/// Must not: canonicalize through the filesystem (the CLI's
/// `RuntimeContext::require_host` and the attach check do that), or be compared
/// as a raw string anywhere outside its own equality.
/// Role: leaf type. `CallerClaim.host`, the target-bearing commands,
/// `CooperativeDecisionFence`, `IntentScope::Cooperative`, `HostIndex` and
/// `HostSessions` depend on it. New host addressing rules go in `parse`; callers
/// never compare raw socket-path strings or canonicalize ad hoc.
/// Errors: `parse` returns `InvalidRequest` with one fixed message.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize)]
#[serde(transparent)]
pub struct HostLocator(String);

/// The one message every rejected locator carries.
const HOST_LOCATOR_INVALID: &str = "host locator is not a canonical absolute path";
const HOST_LOCATOR_MAX_BYTES: usize = 4096;

impl HostLocator {
    pub fn parse(value: impl Into<String>) -> Result<Self, crate::protocol::results::ApiError> {
        let value = value.into();
        let canonical = !value.is_empty()
            && value.len() <= HOST_LOCATOR_MAX_BYTES
            && !value.contains('\0')
            && value.strip_prefix('/').is_some_and(|rest| {
                // A trailing slash (and the bare root) leaves an empty component.
                rest.split('/')
                    .all(|part| !part.is_empty() && part != "." && part != "..")
            });
        if !canonical {
            return Err(crate::protocol::results::ApiError::new(
                crate::protocol::results::ErrorCode::InvalidRequest,
                HOST_LOCATOR_INVALID,
            ));
        }
        Ok(Self(value))
    }
    pub fn as_str(&self) -> &str {
        &self.0
    }
    pub fn as_path(&self) -> &std::path::Path {
        std::path::Path::new(&self.0)
    }
}

impl From<&HostLocator> for std::path::PathBuf {
    fn from(locator: &HostLocator) -> Self {
        locator.as_path().to_path_buf()
    }
}

impl<'de> Deserialize<'de> for HostLocator {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let value = String::deserialize(deserializer)?;
        Self::parse(value).map_err(|error| serde::de::Error::custom(error.detail))
    }
}

#[cfg(test)]
mod public_id_tests {
    use super::*;

    fn tag() -> NodeTag {
        "Q7a".parse().unwrap()
    }

    #[test]
    fn base62_digits_emits_least_significant_first() {
        assert_eq!(base62_digits(0, 3), "000");
        assert_eq!(base62_digits(61, 1), "z");
        assert_eq!(base62_digits(62, 2), "01");
        assert_eq!(base62_digits(62 * 62 + 1, 3), "101");
    }

    #[test]
    fn tagged_shape_for_every_prefix() {
        for prefix in ["s", "t", "i", "q", "r", "e", "p", "m", "np", "n"] {
            let id = generate_public_id(prefix, &tag());
            assert_eq!(id.len(), prefix.len() + NODE_TAG_LEN + PUBLIC_ID_SUFFIX_LEN);
            assert!(id.starts_with(&format!("{prefix}Q7a")), "{id}");
            let (parsed, suffix) = public_id_parts(prefix, &id).unwrap();
            assert_eq!(parsed, tag());
            assert_eq!(suffix.len(), PUBLIC_ID_SUFFIX_LEN);
            assert!(is_public_id(prefix, &id));
            SeatId::parse(id.clone()).unwrap();
            MessageId::parse(id).unwrap();
        }
    }

    #[test]
    fn malformed_ids_are_rejected() {
        assert!(is_public_id("s", "sQ7ak3Fq9a2B"));
        assert!(!is_public_id("s", "sk3Fq9a2B"), "untagged 9-char form");
        assert!(!is_public_id("s", "sQ7ak3Fq9a2"));
        assert!(!is_public_id("s", "sQ7ak3Fq9a2BC"));
        assert!(!is_public_id("s", "sQ7ak3Fq9a2_"));
        assert!(!is_public_id("t", "sQ7ak3Fq9a2B"));
        assert!(!is_public_id(
            "s",
            "seat-bc121d12-9d30-4510-b93c-e7cd26e890f1"
        ));
        assert_eq!(public_id_parts("s", "sQ7ak3Fq9a2B").unwrap().1, "k3Fq9a2B");
    }

    #[test]
    fn n_and_np_disambiguated_by_length() {
        let notify = generate_public_id(prefix::NOTIFY, &tag());
        let prep = generate_public_id(prefix::NOTIFY_PREPARATION, &tag());
        assert_eq!((notify.len(), prep.len()), (12, 13));
        assert!(is_public_id("n", &notify) && !is_public_id("np", &notify));
        assert!(is_public_id("np", &prep) && !is_public_id("n", &prep));
        // A tag starting with `p` is still an `n` id, never an `np` one.
        let p_tag: NodeTag = "pZ9".parse().unwrap();
        let notify = generate_public_id(prefix::NOTIFY, &p_tag);
        assert!(is_public_id("n", &notify) && !is_public_id("np", &notify));
    }

    #[test]
    fn generated_suffixes_are_distinct_and_span_the_alphabet() {
        let mut seen = std::collections::HashSet::new();
        let mut alphabet = std::collections::HashSet::new();
        for _ in 0..4096 {
            let suffix = public_id_suffix();
            alphabet.extend(suffix.bytes());
            assert!(seen.insert(suffix), "suffix repeated within 4096 draws");
        }
        assert_eq!(alphabet.len(), 62, "every base62 digit should appear");
    }

    #[test]
    fn opaque_ids_still_parse() {
        let legacy = "seat-bc121d12-9d30-4510-b93c-e7cd26e890f1";
        assert_eq!(SeatId::parse(legacy).unwrap().as_str(), legacy);
        ThreadId::parse("thread-bc121d12-9d30-4510-b93c-e7cd26e890f1").unwrap();
        InvitationId::parse("invitation-bc121d12-9d30-4510-b93c-e7cd26e890f1").unwrap();
    }

    #[test]
    fn preparation_message_derivation_keeps_tag() {
        assert_eq!(
            send_message_id_for_preparation("pQ7aAb12Cd34"),
            Some("mQ7aAb12Cd34".to_owned())
        );
        assert_eq!(
            notification_message_id_for_preparation("npQ7aAb12Cd34"),
            Some("nQ7aAb12Cd34".to_owned())
        );
        assert_eq!(
            notification_preparation_id_for_message("nQ7aAb12Cd34"),
            Some("npQ7aAb12Cd34".to_owned())
        );
        for rejected in ["broken", "pAb12Cd34", "prep-Ab12Cd34", "npQ7aAb12Cd34"] {
            assert_eq!(
                send_message_id_for_preparation(rejected),
                None,
                "{rejected}"
            );
        }
        assert_eq!(
            notification_preparation_id_for_message("npQ7aAb12Cd34"),
            None
        );
        assert_eq!(
            notification_message_id_for_preparation("nQ7aAb12Cd34"),
            None
        );
        let prep = generate_public_id(prefix::SEND_PREPARATION, &tag());
        let message = send_message_id_for_preparation(&prep).unwrap();
        assert_eq!(public_id_parts("m", &message), public_id_parts("p", &prep));
    }

    fn seat(id: &str) -> SeatId {
        SeatId::new(id)
    }

    #[test]
    fn direct_thread_id_golden_vector() {
        use sha2::{Digest, Sha256};
        let (a, b) = (seat("sAbc12345678"), seat("sXyz98765432"));
        let id = direct_thread_id(&a, &b).unwrap();
        assert_eq!(id.as_str(), "d5hPrtBxfUW");
        // Recompute from the documented byte layout.
        let mut input = b"herdr-threads/direct/v1".to_vec();
        for s in [a.as_str(), b.as_str()] {
            input.extend_from_slice(&(s.len() as u32).to_be_bytes());
            input.extend_from_slice(s.as_bytes());
        }
        let digest = Sha256::digest(&input);
        let mut n = u128::from_be_bytes(digest[..16].try_into().unwrap());
        let mut expected = String::from("d");
        for _ in 0..10 {
            expected.push(char::from(BASE62[(n % 62) as usize]));
            n /= 62;
        }
        assert_eq!(id.as_str(), expected);
    }

    #[test]
    fn direct_thread_id_is_symmetric() {
        let (a, b) = (seat("sAbc12345678"), seat("sXyz98765432"));
        assert_eq!(
            direct_thread_id(&a, &b).unwrap(),
            direct_thread_id(&b, &a).unwrap()
        );
    }

    #[test]
    fn direct_thread_id_same_seat_is_error() {
        let a = seat("sAbc12345678");
        assert_eq!(direct_thread_id(&a, &a), Err(DirectIdError::SameSeat));
    }

    #[test]
    fn direct_thread_id_shape_is_d_plus_10() {
        let id = direct_thread_id(&seat("sAbc12345678"), &seat("sXyz98765432")).unwrap();
        assert_eq!(id.as_str().len(), 11);
        assert!(id.as_str().starts_with(DIRECT_THREAD_PREFIX));
        assert!(is_direct_thread_id(id.as_str()));
        assert!(!is_direct_thread_id("dshort"));
        assert!(!is_direct_thread_id("tAbc1234567"));
        assert!(!is_direct_thread_id("d5hPrtBxfUW1"));
    }

    #[test]
    fn different_pairs_give_different_ids() {
        let seats = [
            "sAbc12345678",
            "sXyz98765432",
            "sQ7ak3Fq9a2B",
            "sAbc1234567",
        ];
        let mut seen = std::collections::HashSet::new();
        for (i, a) in seats.iter().enumerate() {
            for b in &seats[i + 1..] {
                let id = direct_thread_id(&seat(a), &seat(b)).unwrap();
                assert!(seen.insert(id), "{a} {b}");
            }
        }
        assert_eq!(seen.len(), 6);
        // Length prefixes keep concatenation-ambiguous pairs apart.
        assert_ne!(
            direct_thread_id(&seat("ab"), &seat("c")).unwrap(),
            direct_thread_id(&seat("a"), &seat("bc")).unwrap()
        );
    }
}

#[cfg(test)]
mod host_locator_tests {
    use super::*;
    use crate::protocol::results::ErrorCode;

    #[test]
    fn host_locator_accepts_canonical_absolute() {
        let locator = HostLocator::parse("/run/user/1000/herdr.sock").unwrap();
        assert_eq!(locator.as_str(), "/run/user/1000/herdr.sock");
        assert_eq!(
            std::path::PathBuf::from(&locator),
            std::path::PathBuf::from("/run/user/1000/herdr.sock")
        );
        assert!(HostLocator::parse(format!("/{}", "a".repeat(4095))).is_ok());
    }

    #[test]
    fn host_locator_rejects_bad_forms() {
        let too_long = format!("/{}", "a".repeat(4096));
        assert_eq!(too_long.len(), 4097);
        for bad in [
            "",
            "/",
            "relative/path",
            "/a/../b",
            "/a/./b",
            "/a//b",
            "/a/b/",
            "//a",
            "/a/\0b",
            "/..",
            "/.",
            too_long.as_str(),
        ] {
            let error = HostLocator::parse(bad).expect_err(bad);
            assert_eq!(error.code, ErrorCode::InvalidRequest, "{bad:?}");
            assert_eq!(
                error.detail, "host locator is not a canonical absolute path",
                "{bad:?}"
            );
        }
    }

    #[test]
    fn host_locator_serde_is_string() {
        let locator = HostLocator::parse("/tmp/h.sock").unwrap();
        let json = serde_json::to_string(&locator).unwrap();
        assert_eq!(json, "\"/tmp/h.sock\"");
        assert_eq!(serde_json::from_str::<HostLocator>(&json).unwrap(), locator);
        assert!(serde_json::from_str::<HostLocator>("\"a/b\"").is_err());
    }
}
